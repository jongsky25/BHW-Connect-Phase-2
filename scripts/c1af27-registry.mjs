import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {buildPolicyProposal} from './c1af25-policy-proposal.mjs';
import {loadReferenceModule,contentHash} from './lib/reference-content.mjs';
import {beforeFeedbackCsc} from './lib/feedback-csc-preservation.mjs';
const root=process.cwd();
const migration='supabase/migrations/20261015143503_c1af27_disabled_chapter1_registry.sql';
// The historical installer/rehearsals must use the same approved 42-lesson package.
export function registryLesson(lesson){
 if(lesson.manifest.lesson_key!=='bhw-eligibility')return lesson;
 for(const file of ['lesson.json','read.en.md','read.fil.md','slides.json'])beforeFeedbackCsc('content/training/day1-basic-competencies/modules/04-ra7883/lessons/bhw-eligibility/'+file);
 return JSON.parse(readFileSync('content/training/day1-basic-competencies/learner-assessment-v2/releases/chapter1-feedback-accreditation-csc-v3/base-lesson.json'));
}
export function registryPackage(){
 const p=buildPolicyProposal(root);
 const receipt=JSON.parse(readFileSync('docs/chapter-1-assessor-c1af-27-published-revisions.json'));
 const modules=new Map(p.components.map(c=>[c.module_key,c]));
 const lessons=[];
 for(const folder of readdirSync('content/training/day1-basic-competencies/modules')){
  if(!modules.has(folder))continue;
  const m=loadReferenceModule(path.join('content/training/day1-basic-competencies/modules',folder),'public');
  for(const current of m.lessons){
   const lesson=registryLesson(current);
   const proposal=modules.get(folder).required_lessons.find(l=>l.lesson_key===lesson.manifest.lesson_key);
   const published=receipt.rows.find(r=>r.lesson_key===lesson.manifest.lesson_key);
   const hash=contentHash(lesson);
   if(!proposal||!published||published.content_hash!==hash)throw Error('Published lesson differs: '+lesson.manifest.lesson_key);
   lessons.push({module_key:folder,lesson_key:lesson.manifest.lesson_key,content_hash:hash,
    criterion:proposal.criteria[0],title:proposal.title});
  }
 }
 if(lessons.length!==42||new Set(lessons.map(l=>l.criterion.id)).size!==42)throw Error('Expected 42 unique criteria');
 return {requirements_version:p.proposed_requirements_version,curriculum_version:p.curriculum_version,
  rubric_version:p.proposed_rubric_version,award_rule_version:p.proposed_award_rule_version,
  orientation_version:p.staff_award_proposal.orientation_version,simulation:p.staff_award_proposal.simulation,
  issuer:{organization:'DOH',signatory:'Ray Justin Ventura',title:'Chief Health Program Officer'},
  formal_rule:p.formal_rule_proposal,local_safety_rule:p.conflict_decisions_proposed['1.8-safety'],
  decision_reference:'docs/chapter-1-assessor-c1af-27-owner-decision.md',
  decision_sha256_lf:createHash('sha256').update(readFileSync('docs/chapter-1-assessor-c1af-27-owner-decision.md','utf8').replace(/\r\n/g,'\n')).digest('hex'),lessons};
}
const sqlString=v=>"'"+v.replaceAll("'","''")+"'";
export function buildRegistryMigration(){
 const p=registryPackage();
 const body=readFileSync('scripts/lib/c1af27-registry-install.sql','utf8');
 const briefing=readFileSync('supabase/migrations/20261011120608_assessor_briefing_acknowledgement.sql','utf8')
  .match(/create function assessor_rollout_private\.briefing_state[\s\S]*?end;\n\$\$;/)[0]
  .replace('create function','create or replace function')
  .replace("v_requirements constant text:='chapter-1:c1af.draft-1';","v_requirements text;")
  .replace("v_policy:=assessor_rollout_private.policy(p_program_id,'chapter-1');","v_policy:=assessor_rollout_private.policy(p_program_id,'chapter-1');\n v_requirements:=v_policy->>'requirementsVersion';")
  .replace("v_policy->>'requirementsVersion'<>v_requirements","v_requirements not in ('chapter-1:c1af.draft-1','chapter-1:c1af25.pilot-1')");
 const simulation=readFileSync('supabase/migrations/20261012051057_assessor_simulation_runner.sql','utf8')
  .match(/create function assessor_rollout_private\.simulation_state[\s\S]*?end; \$\$;/)[0]
  .replace('create function','create or replace function')
  .replace("return coalesce(s,jsonb_build_object", "if s is not null and s->>'requirementsVersion' is distinct from b->>'requirementsVersion' then\n  raise exception 'archive prior preparation simulation before changing requirements'; end if;\n return coalesce(s,jsonb_build_object")
  .replace("'requirementsVersion','chapter-1:c1af.draft-1'","'requirementsVersion',b->>'requirementsVersion'");
 return '-- Generated by scripts/c1af27-registry.mjs. Disabled registry only.\nbegin;\n'+body.replace('__PACKAGE__',sqlString(JSON.stringify(p)))+'\n'+briefing+'\n'+simulation+'\ncommit;\n';
}
if(process.argv[1]?.endsWith('c1af27-registry.mjs')){
 const sql=buildRegistryMigration();
 if(process.argv.includes('--check')){if(readFileSync(migration,'utf8')!==sql)throw Error('Regenerate C1AF-27 migration after source review');}
 else writeFileSync(migration,sql);
}
